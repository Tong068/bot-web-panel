import assert from 'node:assert/strict'
import path from 'node:path'
import { incoming } from './helpers.mjs'

export async function checkFeatures({ page, context, panel, bot, fixture, output }) {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://localhost:2536' })
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByLabel('选择机器人').selectOption('11')
  await page.getByRole('button', { name: /日常交流群/ }).click()
  await page.getByLabel('消息输入框').waitFor()
  await page.waitForFunction(() => document.querySelector('#main-input-ex') && !document.querySelector('#main-input-ex').disabled)
  const group = page.locator('.friend-body[data-type="group"]'), friend = page.locator('.friend-body[data-type="friend"]')
  const groupAvatar = await group.locator('img').getAttribute('src'), friendAvatar = await friend.locator('img').getAttribute('src')
  assert.match(groupAvatar, /\/api\/media\//); assert.notEqual(groupAvatar, friendAvatar)
  assert.equal(await page.getByAltText('会话头像', { exact: true }).getAttribute('src'), groupAvatar)
  assert.equal(await page.locator('.message:not(.me) > img').first().getAttribute('src'), friendAvatar)
  await page.getByAltText('会话头像', { exact: true }).click()
  assert.equal(await page.locator('.viewer-img').getAttribute('src'), groupAvatar)
  await page.getByLabel('关闭预览').click()

  await group.click({ button: 'right' })
  await page.getByRole('menuitem', { name: '置顶', exact: true }).click()
  await group.locator('.fa-thumbtack').waitFor()
  assert.equal(await page.locator('.friend-body').first().getAttribute('data-type'), 'group')
  await group.focus(); await page.keyboard.press('Shift+F10')
  await page.getByRole('menu', { name: '会话菜单' }).waitFor()
  await page.keyboard.press('End')
  assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), '查看头像')
  await page.keyboard.press('Escape')
  await group.click({ button: 'right' }); await page.getByRole('menuitem', { name: '标记未读', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('#chat-pan'))
  await group.locator('.unread-count').waitFor()
  await group.click({ button: 'right' }); await page.getByRole('menuitem', { name: '复制会话 ID', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '100')
  await page.reload(); await page.getByLabel('选择机器人').waitFor()
  await group.locator('.fa-thumbtack').waitFor(); await group.locator('.unread-count').waitFor()
  await page.getByLabel('选择机器人').selectOption('22')
  await page.waitForFunction(() => document.querySelector('.friend-body[data-type="group"]')?.textContent.includes('另一个账号'))
  assert.equal(await page.locator('.friend-body .fa-thumbtack').count(), 0)
  await page.getByLabel('选择机器人').selectOption('11')
  await group.click(); await page.getByLabel('消息输入框').waitFor()

  const longText = '完整复制校验'.repeat(100)
  bot.emit('message', incoming('11', 'group', 'copy-long', longText)); await panel.bridge.tasks
  const longMessage = page.locator('.message').filter({ hasText: longText })
  await longMessage.click({ button: 'right' })
  await page.getByRole('menuitem', { name: '复制', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), longText)
  await longMessage.locator('.msg-text').evaluate(element => {
    const range = document.createRange(); range.setStart(element.firstChild, 2); range.setEnd(element.firstChild, 12)
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range)
  })
  await longMessage.dispatchEvent('contextmenu', { clientX: 900, clientY: 400 })
  await page.getByRole('menuitem', { name: '复制选中文本', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), longText.slice(2, 12))
  await longMessage.click({ button: 'right' }); await page.getByRole('menuitem', { name: '@发送者', exact: true }).click()
  assert.equal(await page.locator('.mention-chip').count(), 1)
  await page.locator('.mention-chip').click()
  await longMessage.click({ button: 'right' }); await page.getByRole('menuitem', { name: '复制消息 ID', exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'copy-long')
  const imageMessage = page.locator('.message').filter({ has: page.locator('img.msg-img') }).first()
  await imageMessage.scrollIntoViewIfNeeded(); await imageMessage.click({ button: 'right' })
  const download = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: '下载图片', exact: true }).click()
  assert.equal(await (await download).failure(), null)

  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('自动深色模式', { exact: true }).check()
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.waitForFunction(() => document.querySelector('#theme-colors').href.endsWith('color-dark.css'))
  await page.getByRole('radio', { name: '草绿', exact: true }).check()
  await page.getByLabel('独立显示消息', { exact: true }).uncheck()
  await page.getByLabel('会话显示', { exact: true }).selectOption('all')
  const swatches = await page.getByRole('radiogroup', { name: '主题色' }).locator('label').evaluateAll(items => items.map(item => ({ width: item.offsetWidth, height: item.offsetHeight, colorWidth: item.lastElementChild.offsetWidth, colorHeight: item.lastElementChild.offsetHeight })))
  assert.ok(swatches.every(box => box.width === 32 && box.height === 32 && box.colorWidth === 24 && box.colorHeight === 24), JSON.stringify(swatches))
  await page.waitForTimeout(450)
  await page.screenshot({ path: path.join(output, 'settings-desktop-dark.png') })
  await page.getByRole('tab', { name: '聊天', exact: true }).click()
  await page.getByLabel('发送键', { exact: true }).selectOption('ctrl')
  await page.getByLabel('不自动加载图片', { exact: true }).check()
  await page.getByLabel('关闭设置').click()
  assert.equal(await page.locator('.message.me.right').count(), 0)
  await page.getByRole('button', { name: '加载图片', exact: true }).first().scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: '加载图片', exact: true }).first().click()
  await page.locator('img.msg-img').first().waitFor()
  const count = fixture.calls.length
  await page.getByLabel('消息输入框').fill('组合键校验')
  await page.getByLabel('消息输入框').press('Enter')
  assert.equal(fixture.calls.length, count)
  assert.equal(await page.getByLabel('消息输入框').inputValue(), '组合键校验\n')
  await page.getByLabel('消息输入框').press('Control+Enter')
  await page.waitForFunction(() => !document.querySelector('.send-button').disabled)
  assert.equal(fixture.calls.length, count + 1)
  await page.reload(); await page.getByLabel('消息输入框').waitFor()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  assert.equal(await page.getByLabel('自动深色模式', { exact: true }).isChecked(), true)
  assert.equal(await page.getByRole('radio', { name: '草绿', exact: true }).isChecked(), true)
  assert.equal(await page.getByLabel('独立显示消息', { exact: true }).isChecked(), false)
  await page.getByRole('tab', { name: '聊天', exact: true }).click()
  assert.equal(await page.getByLabel('发送键', { exact: true }).inputValue(), 'ctrl')
  assert.equal(await page.getByLabel('不自动加载图片', { exact: true }).isChecked(), true)
  await page.getByLabel('关闭设置').click()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('返回会话列表').click()
  const box = await group.boundingBox()
  await group.dispatchEvent('pointerdown', { pointerType: 'touch', clientX: box.x + 30, clientY: box.y + 20 })
  await page.getByRole('menu', { name: '会话菜单' }).waitFor()
  await group.dispatchEvent('pointerup', { pointerType: 'touch' })
  await page.screenshot({ path: path.join(output, 'conversation-menu-mobile.png') })
  await page.keyboard.press('Escape')
  await group.dispatchEvent('pointerdown', { pointerType: 'touch', clientX: box.x + 30, clientY: box.y + 20 })
  await group.dispatchEvent('pointermove', { pointerType: 'touch', clientX: box.x + 30, clientY: box.y + 90 })
  await group.dispatchEvent('pointerup', { pointerType: 'touch' }); await page.waitForTimeout(850)
  assert.equal(await page.getByRole('menu').count(), 0)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'settings-mobile.png') })
  const layout = await page.getByRole('dialog', { name: '设置', exact: true }).evaluate(element => ({ width: element.clientWidth, content: element.scrollWidth }))
  assert.ok(layout.content <= layout.width, JSON.stringify(layout))
  await page.getByLabel('关闭设置').click()
  await group.click(); await page.getByLabel('消息输入框').waitFor()
  const lastMessage = page.locator('.message').last()
  await lastMessage.evaluate(element => element.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: 387, clientY: 840 })))
  const menuBox = await page.getByRole('menu', { name: '消息菜单' }).boundingBox()
  assert.ok(menuBox.x >= 8 && menuBox.y >= 8 && Math.abs(menuBox.x + menuBox.width - 382) < 1 && Math.abs(menuBox.y + menuBox.height - 836) < 1, JSON.stringify(menuBox))
  await page.screenshot({ path: path.join(output, 'message-menu-mobile.png') })
  await page.keyboard.press('Escape')
  await lastMessage.dispatchEvent('contextmenu')
  const fallbackBox = await page.getByRole('menu', { name: '消息菜单' }).boundingBox()
  assert.ok(fallbackBox.x >= 8 && fallbackBox.y >= 8 && fallbackBox.x + fallbackBox.width <= 382 && fallbackBox.y + fallbackBox.height <= 836, JSON.stringify(fallbackBox))
  await page.keyboard.press('Escape')
  await page.screenshot({ path: path.join(output, 'avatars-mobile-dark.png') })
}
